from ..llm.client import ask_llm


def fact_checker(state):

    prompt = f"""
Проверь приведённый ниже анализ документа.

ИСХОДНЫЙ ТЕКСТ ДОКУМЕНТА:

{state["text"]}

АНАЛИЗ:

{state["analysis"]}

КРАТКОЕ СОДЕРЖАНИЕ:

{state["summary"]}

Определи:

1. Какие утверждения выглядят как факты.

2. Есть ли противоречия или сомнительные утверждения.

3. Есть ли утверждения, которые нельзя подтвердить только по представленному тексту.

4. Попытайся выявить любые логические несоответствия или ошибки в рассуждениях.

5. Есть ли утверждения, кажущиеся похожими на нейросетевые галлюцинации
(т.е. факты, которые не подтверждаются текстом и не являются общепринятыми знаниями).

6. Есть ли ложные следы, созданные нейросетевыми генеративными моделями,
которые могут ввести в заблуждение относительно содержания документа.

7. Есть ли противоречия между анализом и кратким содержанием документа.

8. Правильно ли сделан вывод о достоверности анализа документа.

Важно:

Не используй внешние источники.

Проверяй только внутреннюю логическую согласованность текста.

Дай краткий результат проверки и почему ты считаешь так.

Обязательно укажи, какие утверждения вызывают сомнения и почему.

Обязательно укажи, сомневаешься ли ты в достоверности анализа или нет.
Если сомневаешься, укажи, в чем ты не уверен и почему.

"""


    facts = ask_llm(prompt, "Fact Checker")

    return {
        "facts": facts
    }