from ..llm.client import ask_llm


def final_agent(state):

    prompt = f"""
Ты формируешь итоговый результат анализа документа.

Результаты предыдущих агентов:

АНАЛИЗ:
{state["analysis"]}

КРАТКОЕ СОДЕРЖАНИЕ:
{state["summary"]}

ПРОВЕРКА ФАКТОВ:
{state["facts"]}

Сформируй итоговый ответ пользователю.

Ответ должен содержать:

1. Краткое содержание документа.
2. Основные идеи и выводы.
3. Результат проверки анализа.
4. Сомнительные или неподтверждённые утверждения, если они есть.
5. Общий вывод.

Не добавляй информацию, которой нет в результатах предыдущих агентов.
Не используй внешние источники.
"""

    final = ask_llm(prompt)

    return {
        "final": final
    }